package com.groupthree.Facilitybook.entity;

import jakarta.persistence.Column;
import jakarta.persistence.MappedSuperclass;
import jakarta.persistence.PrePersist;
import jakarta.persistence.PreUpdate;
import lombok.Getter;

import java.time.Instant;

/**
 * Shared created_at / updated_at handling for tables that have both columns.
 * Values are set by the application because the database defaults only apply on insert.
 */
@MappedSuperclass
@Getter
public abstract class AuditableEntity {

    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    @Column(name = "updated_at", nullable = false)
    private Instant updatedAt;

    @PrePersist
    void applyCreatedTimestamps() {
        Instant now = Instant.now();
        if (createdAt == null) {
            createdAt = now;
        }
        updatedAt = now;
    }

    @PreUpdate
    void applyUpdatedTimestamp() {
        updatedAt = Instant.now();
    }
}
